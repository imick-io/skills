#!/usr/bin/env node
// The deterministic half of /run-design-epic's design rounds. /run-epic's own
// script still claims, prepares, lands and finishes; this one only handles
// what a round adds. Run from the repo root:
//
//   node <skill>/scripts/design.mjs check <epic>                  capture recipe, tools, checkpoints (JSON)
//   node <skill>/scripts/design.mjs round <ticket> <k>            make round k's folder, note the commit it photographs (JSON)
//   node <skill>/scripts/design.mjs prompt <capture|review|fix> <ticket> <k>   the round's prompt, filled in
//   node <skill>/scripts/design.mjs captured <ticket> <k>         how many pictures, and is the worktree clean (JSON)
//   node <skill>/scripts/design.mjs verdict <ticket> <k>          the reviewer's verdict (JSON)
//   node <skill>/scripts/design.mjs checkpoint <ticket>           true when the ticket pauses for approval
//   node <skill>/scripts/design.mjs publish <ticket>              findings on the issue, review page rebuilt (JSON)
//   node <skill>/scripts/design.mjs page <epic>                   rebuild the review page, print its path
//
// Pictures and reviews live under .claude/design-runs/<epic>/<ticket>/round-<k>/,
// on this machine only. Round 1 photographs every screen in scope; a later round
// re-photographs only what changed since the round before, so a ticket's latest
// picture of a screen may sit in an earlier round's folder. JSON goes to stdout; a stop is a `## Heading` and a
// Markdown reason on stdout with exit code 1.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const [cmd, ...rest] = process.argv.slice(2);
const args = rest.filter((a) => !a.startsWith("--")).map((a) => a.replace(/^#/, ""));

const run = (c, argv, opts = {}) => {
  try {
    return { ok: true, out: execFileSync(c, argv, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 * 1024 * 1024, ...opts }).trim() };
  } catch (e) {
    return { ok: false, out: String(e.stdout ?? "").trim(), err: String(e.stderr ?? e.message).trim() };
  }
};
const must = (c, argv, opts) => {
  const r = run(c, argv, opts);
  if (!r.ok) throw new Error(`${c} ${argv.join(" ")}\n${r.err}`);
  return r.out;
};
const git = (...a) => must("git", a);
const gh = (...a) => must("gh", a);
const ghJson = (...a) => JSON.parse(gh(...a));
const json = (o) => console.log(JSON.stringify(o, null, 2));
const stop = (why, heading = "Stopped") => {
  console.log(`## ${heading}\n\n${why}`);
  process.exit(1);
};
const AI_NOTE = "> *This was generated by AI in /run-design-epic, the agent loop's pipeline run in a session with design rounds.*";
const MAX_ROUNDS = 3;
const CHECKPOINT = /^#{2,3}\s+Design checkpoint\s*$/m;

if (!run("git", ["rev-parse", "--is-inside-work-tree"]).ok) stop("Run this from the project's repo.");
const top = git("rev-parse", "--show-toplevel");
process.chdir(top);

const RUNS = join(top, ".claude", "design-runs");
const CAPTURE_DOC = "docs/agents/design-capture.md";
const wtPath = (n) => join(top, ".claude", "worktrees", `run-epic-${n}`);

const epicLabel = "epic";

const readEpic = (n) => {
  const e = ghJson("issue", "view", String(n), "--json", "number,title,body,labels,milestone");
  if (!e.labels.some((l) => l.name === epicLabel)) stop(`#${n} isn't an epic.`);
  if (!e.milestone?.title) stop(`Epic #${n} has no milestone; its tickets are found through it.`);
  const branch = e.body.match(/`(epic\/[^`]+)`/)?.[1];
  return { number: e.number, title: e.title, body: e.body, milestone: e.milestone.title, branch };
};

const ticketOf = (n) => {
  const i = ghJson("issue", "view", String(n), "--json", "number,title,body,milestone");
  if (!i.milestone?.title) stop(`#${n} has no milestone, so no epic.`);
  const [e] = ghJson("issue", "list", "--state", "open", "--label", epicLabel, "--milestone", i.milestone.title, "--json", "number", "--limit", "1");
  if (!e) stop(`No open epic owns #${n}'s milestone "${i.milestone.title}".`);
  return { number: i.number, title: i.title, body: i.body, epic: readEpic(e.number), branch: `agent/issue-${i.number}` };
};

const roundDir = (t, k) => join(RUNS, String(t.epic.number), String(t.number), `round-${k}`);
const roundOf = (k) => {
  const n = Number(k);
  if (!Number.isInteger(n) || n < 1 || n > MAX_ROUNDS) stop(`A round is 1 to ${MAX_ROUNDS}.`);
  return n;
};
const readJson = (f) => {
  try { return JSON.parse(readFileSync(f, "utf8")); } catch { return undefined; }
};
const images = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => /\.(png|jpe?g|webp)$/i.test(f)).sort() : []);
const rounds = (ticketDir) =>
  existsSync(ticketDir)
    ? readdirSync(ticketDir).map((d) => Number(d.match(/^round-(\d+)$/)?.[1])).filter(Boolean).sort((a, b) => a - b)
    : [];
// Each picture's latest version across a ticket's rounds, oldest round first.
const latestImages = (ticketDir) => {
  const byFile = new Map();
  for (const k of rounds(ticketDir)) {
    const dir = join(ticketDir, `round-${k}`);
    const meta = Object.fromEntries((readJson(join(dir, "shots.json"))?.shots ?? []).map((s) => [s.file, s]));
    for (const f of images(dir)) byFile.set(f, { file: f, dir, meta: meta[f] });
  }
  return [...byFile.values()].sort((a, b) => a.file.localeCompare(b.file));
};
const counts = (review) => ({
  must: (review?.findings ?? []).filter((f) => f.severity === "must").length,
  should: (review?.findings ?? []).filter((f) => f.severity !== "must").length,
});
const findingsMd = (review) =>
  (review?.findings ?? []).length
    ? review.findings.map((f, i) => `${i + 1}. **${f.severity === "must" ? "must" : "should"}** · ${f.screen}${f.files?.length ? ` (${f.files.map((x) => `\`${x}\``).join(", ")})` : ""}\n   - What: ${f.issue}\n   - Fix: ${f.fix}`).join("\n")
    : "No findings.";

const designRefs = () => {
  const refs = [];
  if (existsSync("docs/design")) refs.push("the boards in `docs/design/` (open the files that cover this ticket's screens)");
  refs.push("every reference the ticket links (boards by ID, Mobbin links)", "the epic's body (its rules and direction)");
  return refs.join("; ");
};

const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

// One self-contained page per epic: each ticket's last round, its pictures
// and the reviewer's findings. Images are linked by relative path.
const buildPage = (epic) => {
  const epicDir = join(RUNS, String(epic.number));
  mkdirSync(epicDir, { recursive: true });
  const tickets = readdirSync(epicDir).filter((d) => /^\d+$/.test(d)).sort((a, b) => Number(a) - Number(b));
  const sections = tickets.map((n) => {
    const ks = rounds(join(epicDir, n));
    if (!ks.length) return "";
    const k = ks[ks.length - 1];
    const dir = join(epicDir, n, `round-${k}`);
    const review = readJson(join(dir, "review.json"));
    const shots = readJson(join(dir, "shots.json"));
    const title = readJson(join(epicDir, n, "ticket.json"))?.title ?? "";
    const c = counts(review);
    const verdict = !review ? "not reviewed" : c.must ? `${c.must} must, ${c.should} should` : c.should ? `pass, ${c.should} should` : "pass";
    const pics = latestImages(join(epicDir, n)).map(({ file: f, dir: from, meta: m }) => {
      const cap = m ? [m.screen, m.state, m.viewport, m.theme].filter(Boolean).join(" · ") : f;
      const src = relative(epicDir, join(from, f)).split("\\").join("/");
      return `<figure><a href="${esc(src)}"><img loading="lazy" src="${esc(src)}" alt="${esc(cap)}"></a><figcaption>${esc(cap)}</figcaption></figure>`;
    }).join("");
    const list = (review?.findings ?? []).map((f) => `<li class="${f.severity === "must" ? "must" : "should"}"><b>${esc(f.severity === "must" ? "must" : "should")}</b> ${esc(f.screen)}: ${esc(f.issue)} <span>Fix: ${esc(f.fix)}</span></li>`).join("");
    const missed = (shots?.missed ?? []).map((m) => `<li>${esc(m.screen)}${m.state ? ` (${esc(m.state)})` : ""}: ${esc(m.why)}</li>`).join("");
    return `<section id="t${n}"><h2>#${n} ${esc(title)}</h2><p class="meta">Round ${k} of ${ks.length} · <span class="${c.must ? "bad" : "ok"}">${esc(verdict)}</span></p>${review?.summary ? `<p>${esc(review.summary)}</p>` : ""}${list ? `<ul class="findings">${list}</ul>` : ""}${missed ? `<details><summary>Not photographed</summary><ul>${missed}</ul></details>` : ""}<div class="grid">${pics || "<p>No pictures.</p>"}</div></section>`;
  }).join("\n");
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Design review: ${esc(epic.title)}</title><style>
:root{color-scheme:light dark;--bg:#f6f6f4;--fg:#1c1c1a;--mut:#666;--line:#ddd;--card:#fff;--bad:#b3323f;--ok:#0c7a5c}
@media(prefers-color-scheme:dark){:root{--bg:#121212;--fg:#eee;--mut:#9a9a9a;--line:#333;--card:#1c1c1c;--bad:#f08a95;--ok:#4fd8a8}}
body{margin:0;padding:24px 16px 64px;background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif}
main{max-width:1280px;margin:0 auto}h1{font-size:24px;margin:0 0 4px}h2{font-size:18px;margin:0}
section{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:16px;margin-top:20px}
.meta{color:var(--mut);margin:2px 0 10px}.bad{color:var(--bad);font-weight:600}.ok{color:var(--ok);font-weight:600}
.findings{padding-left:18px}.findings li{margin-bottom:6px}.findings span{display:block;color:var(--mut)}.must b{color:var(--bad)}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(260px,1fr));gap:12px;margin-top:12px}
figure{margin:0}img{width:100%;border:1px solid var(--line);border-radius:6px;display:block}figcaption{font-size:12px;color:var(--mut);margin-top:4px}
nav a{margin-right:12px;color:inherit}
</style></head><body><main><h1>Design review: ${esc(epic.title)}</h1><p class="meta">Epic #${epic.number} · each ticket's latest round · built ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC</p><nav>${tickets.map((n) => `<a href="#t${n}">#${n}</a>`).join("")}</nav>${sections || "<p>No rounds yet.</p>"}</main></body></html>`;
  const file = join(epicDir, "index.html");
  writeFileSync(file, html);
  return file;
};

const firstScope = (path, base) => {
  const changed = run("git", ["-C", path, "diff", "--name-only", `${base}...HEAD`]).out || "(no changed files found)";
  return `A screen is in scope when the ticket names it, or when the ticket's commits touch it:\n\n\`\`\`\n${changed}\n\`\`\``;
};

// Round 2 and 3 re-photograph only what the fixes could have changed.
const laterScope = (path, prev) => {
  const from = readJson(join(prev, "round.json"))?.head;
  const diff = from ? run("git", ["-C", path, "diff", "--name-only", `${from}..HEAD`]) : undefined;
  const changed = !diff?.ok ? "(no record of the previous round's commit: treat every screen as changed)" : diff.out || "(no code changed since the previous round)";
  const named = [...new Set((readJson(join(prev, "review.json"))?.findings ?? []).flatMap((f) => f.files ?? []))];
  return [
    `This is a re-check. The previous round photographed every screen in scope: \`${join(prev, "shots.json")}\` lists them, and they stand. Re-photograph only:`,
    "",
    "1. every picture a previous finding names, with the same file name, so the reviewer compares like with like:",
    "",
    named.length ? named.map((f) => `   - \`${f}\``).join("\n") : "   - (none named)",
    "",
    "2. every screen whose code changed since the previous round, in all of its states, viewports and themes as the previous round took them. The changes:",
    "",
    "```",
    changed,
    "```",
    "",
    "3. **every screen of the previous round** when a change reaches code that many screens share (the design system's components or tokens, a layout or the app's shell): a shared change can break a screen nobody touched.",
    "",
    "Use the previous round's plan, names and states for each picture you retake. A screen the previous round missed and the fixes now make reachable is in scope too.",
  ].join("\n");
};

const commands = {
  check([n]) {
    if (!n) stop("Usage: check <epic>");
    const epic = readEpic(n);
    const issues = ghJson("issue", "list", "--state", "open", "--milestone", epic.milestone, "--json", "number,title,body", "--limit", "200");
    const has = (c) => run("sh", ["-c", `command -v ${c}`]).ok;
    const sim = run("xcrun", ["simctl", "list", "devices", "booted"]);
    mkdirSync(RUNS, { recursive: true });
    if (!existsSync(join(RUNS, ".gitignore"))) writeFileSync(join(RUNS, ".gitignore"), "*\n");
    json({
      epic: { number: epic.number, title: epic.title },
      captureDoc: existsSync(CAPTURE_DOC) ? CAPTURE_DOC : null,
      lanes: existsSync(CAPTURE_DOC) && /^#{2,3}\s+Lanes\s*$/m.test(readFileSync(CAPTURE_DOC, "utf8")),
      designRefs: existsSync("docs/design") ? "docs/design" : null,
      tools: { agentBrowser: has("agent-browser"), maestro: has("maestro"), bootedSimulator: sim.ok && /\(Booted\)/.test(sim.out) },
      checkpoints: issues.filter((i) => i.number !== epic.number && CHECKPOINT.test(i.body)).map((i) => ({ number: i.number, title: i.title })),
      maxRounds: MAX_ROUNDS,
      page: join(RUNS, String(epic.number), "index.html"),
    });
  },

  round([n, k]) {
    if (!n || !k) stop("Usage: round <ticket> <k>");
    const t = ticketOf(n);
    const dir = roundDir(t, roundOf(k));
    mkdirSync(dir, { recursive: true });
    const head = run("git", ["-C", wtPath(n), "rev-parse", "HEAD"]);
    if (head.ok) writeFileSync(join(dir, "round.json"), JSON.stringify({ head: head.out }));
    if (!existsSync(join(RUNS, ".gitignore"))) writeFileSync(join(RUNS, ".gitignore"), "*\n");
    writeFileSync(join(RUNS, String(t.epic.number), String(t.number), "ticket.json"), JSON.stringify({ number: t.number, title: t.title }));
    json({ ticket: t.number, round: Number(k), dir, shots: join(dir, "shots.json"), review: join(dir, "review.json") });
  },

  prompt([kind, n, k]) {
    if (!["capture", "review", "fix"].includes(kind) || !n || !k) stop("Usage: prompt <capture|review|fix> <ticket> <k>");
    const t = ticketOf(n);
    const round = roundOf(k);
    const dir = roundDir(t, round);
    if (!existsSync(dir)) stop(`No folder for round ${round}: run \`round ${n} ${round}\` first.`);
    const path = wtPath(n);
    if (kind !== "review" && !existsSync(path)) stop(`No worktree for #${n}: \`run-epic prepare ${n}\` first.`);
    if (kind === "capture" && !existsSync(CAPTURE_DOC)) stop(`\`${CAPTURE_DOC}\` doesn't exist: the project has no capture recipe.`);
    const base = t.epic.branch ? `origin/${t.epic.branch}` : "origin/main";
    let scope = "";
    if (kind === "capture") scope = round === 1 ? firstScope(path, base) : laterScope(path, roundDir(t, round - 1));
    let previous = "";
    if (kind === "review" && round > 1) {
      const prev = roundDir(t, round - 1);
      previous = `4. The previous round's review, \`${join(prev, "review.json")}\`: check that each of its \`must\` findings is fixed in this round's pictures. One that is not stays a \`must\`. This round re-photographed only what changed since then (the fixes' screens and the pictures the findings named); the previous round's other pictures stand as reviewed. Judge every picture here in full, as in round 1: a fix that broke something else on its screen is a finding.`;
    }
    const review = kind === "fix" ? readJson(join(dir, "review.json")) : undefined;
    if (kind === "fix" && !review) stop(`Round ${round} has no review.json to fix from.`);
    const text = readFileSync(join(HERE, "..", `${kind}-prompt.md`), "utf8")
      .replaceAll("{{ISSUE}}", String(t.number)).replaceAll("{{TITLE}}", t.title).replaceAll("{{ROUND}}", String(round))
      .replaceAll("{{WORKTREE}}", path).replaceAll("{{BRANCH}}", t.branch).replaceAll("{{DIR}}", dir)
      .replaceAll("{{CAPTURE_DOC}}", CAPTURE_DOC).replaceAll("{{SCOPE}}", scope)
      .replaceAll("{{DESIGN_REFS}}", designRefs()).replaceAll("{{PREVIOUS}}", previous)
      .replaceAll("{{FINDINGS}}", findingsMd(review)).replaceAll("{{BODY}}", t.body);
    process.stdout.write(text + "\n");
  },

  captured([n, k]) {
    if (!n || !k) stop("Usage: captured <ticket> <k>");
    const t = ticketOf(n);
    const dir = roundDir(t, roundOf(k));
    const shots = readJson(join(dir, "shots.json"));
    const path = wtPath(n);
    const dirty = existsSync(path) ? run("git", ["-C", path, "status", "--porcelain"]).out.split("\n").filter(Boolean) : [];
    json({ images: images(dir).length, listed: shots?.shots?.length ?? 0, missed: shots?.missed ?? [], worktreeDirty: dirty });
  },

  verdict([n, k]) {
    if (!n || !k) stop("Usage: verdict <ticket> <k>");
    const t = ticketOf(n);
    const round = roundOf(k);
    const dir = roundDir(t, round);
    const review = readJson(join(dir, "review.json"));
    if (!review) stop(`Round ${round} has no readable review.json: the reviewer didn't finish.`);
    const unseen = images(dir).filter((f) => !(review.seen ?? []).includes(f));
    const c = counts(review);
    json({ pass: c.must === 0, ...c, unseen, lastRound: round >= MAX_ROUNDS, summary: review.summary ?? "" });
  },

  checkpoint([n]) {
    if (!n) stop("Usage: checkpoint <ticket>");
    console.log(CHECKPOINT.test(ticketOf(n).body) ? "true" : "false");
  },

  publish([n]) {
    if (!n) stop("Usage: publish <ticket>");
    const t = ticketOf(n);
    const ks = rounds(join(RUNS, String(t.epic.number), String(t.number)));
    if (!ks.length) stop(`#${n} has no design round.`);
    const k = ks[ks.length - 1];
    const dir = roundDir(t, k);
    const review = readJson(join(dir, "review.json"));
    const shots = readJson(join(dir, "shots.json"));
    const c = counts(review);
    const page = buildPage(t.epic);
    const pictures = latestImages(join(RUNS, String(t.epic.number), String(t.number))).length;
    const head = !review ? "The screens were not reviewed." : c.must ? `**${c.must} must-fix finding${c.must === 1 ? "" : "s"} still open** after round ${k}.` : `**Passed** in round ${k}${c.should ? `, with ${c.should} smaller finding${c.should === 1 ? "" : "s"} left` : ""}.`;
    const missed = (shots?.missed ?? []).length ? `\n\nNot photographed:\n${shots.missed.map((m) => `- ${m.screen}${m.state ? ` (${m.state})` : ""}: ${m.why}`).join("\n")}` : "";
    const body = `${AI_NOTE}\n\n## Design review\n\n${head} ${pictures} screenshots reviewed.${review?.summary ? `\n\n${review.summary}` : ""}\n\n${review ? findingsMd(review) : ""}${missed}\n\nThe pictures are on the machine that ran it: \`${relative(top, page)}\`.`;
    gh("issue", "comment", String(n), "--body", body);
    json({ published: Number(n), round: k, ...c, page });
  },

  page([n]) {
    if (!n) stop("Usage: page <epic>");
    console.log(buildPage(readEpic(n)));
  },
};

if (!commands[cmd]) stop(`Unknown command \`${cmd ?? ""}\`. See the header of this script.`);
commands[cmd](args);
