#!/usr/bin/env node
// The agent loop's per-ticket pipeline, as subcommands for /run-ticket, which
// runs it inside a Claude Code session on one ticket. Run from the repo root:
//
//   node <skill>/scripts/run-ticket.mjs check <ticket> [--force]   can it run here? (JSON)
//   node <skill>/scripts/run-ticket.mjs prepare <ticket> [--retry]  claim, base updated, ticket branch + worktree (JSON)
//   node <skill>/scripts/run-ticket.mjs prompt <implement|bug|review> <ticket>   the loop's prompt, filled in
//   node <skill>/scripts/run-ticket.mjs commits <ticket>      commits on the ticket branch not yet on its base
//   node <skill>/scripts/run-ticket.mjs land <ticket>         epic: merge onto the epic branch, push, close (exit 3 on
//                                                             conflict), open the epic's PR when it was the last ticket;
//                                                             no epic: push, PR to main with "Fixes #n" (JSON)
//   node <skill>/scripts/run-ticket.mjs handback <ticket> <reason>   to a person: label, comment, unassign
//   node <skill>/scripts/run-ticket.mjs notify <feed|alert> <text>   Slack, when the loop's webhooks are configured
//
// Every step mirrors .sandcastle/main.mts (claim, prepareEpic, prepareBranch,
// build, settle, land) and /run-epic's script, so a ticket built this way is
// indistinguishable from one the loop built: under an epic it lands on the
// epic branch and closes; otherwise it arrives as a PR to main. The judgement
// half (dispatching the agents, deciding what a run without commits means) is
// the skill's; this file only does the deterministic part. JSON goes to
// stdout; a stop is a `## Heading` and a Markdown reason on stdout with exit
// code 1 (2: the loop may be building it; 3: a merge conflict at landing).

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const [cmd, ...rest] = process.argv.slice(2);
const flags = new Set(rest.filter((a) => a.startsWith("--")));
const args = rest.filter((a) => !a.startsWith("--")).map((a) => a.replace(/^#/, ""));

// ---- helpers (as in run-epic.mjs and claim.mjs)

const run = (c, argv, opts = {}) => {
  try {
    return { ok: true, out: execFileSync(c, argv, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 * 1024 * 1024, ...opts }).trim() };
  } catch (e) {
    return { ok: false, out: String(e.stdout ?? "").trim(), err: String(e.stderr ?? e.message).trim() };
  }
};
const must = (c, argv, opts) => {
  const r = run(c, argv, opts);
  if (!r.ok) throw new Error(`${c} ${argv.join(" ")}\n${r.err}`);
  return r.out;
};
const git = (...a) => must("git", a);
const tryGit = (...a) => run("git", a).ok;
const gh = (...a) => must("gh", a);
const ghJson = (...a) => JSON.parse(gh(...a));
const json = (o) => console.log(JSON.stringify(o, null, 2));
const stop = (why, heading = "Stopped", code = 1) => {
  console.log(`## ${heading}\n\n${why}`);
  process.exit(code);
};
const AI_NOTE = "> *This was generated by AI in /run-ticket, the agent loop's pipeline run in a session.*";

// ---- labels: docs/agents/triage-labels.md maps each role to this repo's label

const LABEL = { build: "ready-for-agent", bug: "ready-for-agent-debugging", human: "ready-for-human", review: "ready-for-review", spec: "spec", backlog: "backlog", manual: "manual", epic: "epic" };
if (existsSync("docs/agents/triage-labels.md")) {
  const roles = { "ready-for-agent": "build", "ready-for-agent-debugging": "bug", "ready-for-human": "human", "ready-for-review": "review", spec: "spec", backlog: "backlog", manual: "manual" };
  for (const line of readFileSync("docs/agents/triage-labels.md", "utf8").split("\n")) {
    const cells = line.split("|").map((c) => c.trim().replace(/`/g, ""));
    if (cells.length > 4 && roles[cells[1]] && cells[3]) LABEL[roles[cells[1]]] = cells[3];
  }
}

// ---- where we are

if (!run("git", ["rev-parse", "--is-inside-work-tree"]).ok) stop("Run this from the project's repo.");
const top = git("rev-parse", "--show-toplevel");
process.chdir(top);
const repo = run("gh", ["repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"]).out || "repo";
const me = run("gh", ["api", "user", "--jq", ".login"]).out;
const WORKTREES = join(top, ".claude", "worktrees");
const wtPath = (n) => join(WORKTREES, `run-ticket-${n}`);

const isSpec = (labels, body) => labels.includes(LABEL.spec) || (/^## Problem Statement/m.test(body) && /^## User Stories/m.test(body));
const blockers = (n) => ghJson("api", `repos/{owner}/{repo}/issues/${n}/dependencies/blocked_by`, "--jq", '[.[] | select(.state == "open") | .number]');
const blockedCount = (n) => Number(gh("api", `repos/{owner}/{repo}/issues/${n}`, "--jq", ".issue_dependencies_summary.blocked_by // 0"));

// The epic owning a milestone, as the loop finds it (everything under an epic
// carries its milestone). Undefined: the ticket stands alone.
const epicFor = (milestone) => {
  if (!milestone) return undefined;
  const [e] = ghJson("issue", "list", "--state", "open", "--label", LABEL.epic, "--milestone", milestone, "--json", "number,title,body,labels", "--limit", "1");
  if (!e) return undefined;
  const branch = e.body.match(/`(epic\/[^`]+)`/)?.[1];
  if (!branch) stop(`Epic #${e.number}'s body names no \`epic/NN-slug\` branch, so #${args[0]} has nowhere to land; /scope-decomposer writes one.`);
  const labels = e.labels.map((l) => l.name);
  return { number: e.number, title: e.title, body: e.body, branch, milestone, labels, manual: labels.includes(LABEL.manual) };
};

const ticketOf = (n) => {
  const i = ghJson("issue", "view", String(n), "--json", "number,title,state,body,labels,milestone,assignees");
  const labels = i.labels.map((l) => l.name);
  const kind = labels.includes(LABEL.bug) || (labels.includes("bug") && !labels.includes(LABEL.build)) ? "bug" : "build";
  const epic = epicFor(i.milestone?.title);
  // The loop's branch names: agent/issue-N off the epic branch, else
  // feat/N (fix/N for a bug) off main.
  const branch = epic ? `agent/issue-${i.number}` : `${kind === "bug" ? "fix" : "feat"}/${i.number}`;
  return { number: i.number, title: i.title, state: i.state, body: i.body, labels, assignees: i.assignees.map((a) => a.login), kind, epic, branch, baseRef: epic ? epic.branch : "main", base: `origin/${epic ? epic.branch : "main"}` };
};

// The worktree holding a branch, if any (the loop keeps its own under
// .sandcastle/worktrees/, this skill under .claude/worktrees/run-ticket-<n>).
const branchWorktree = (branch) => {
  for (const block of git("worktree", "list", "--porcelain").split("\n\n")) {
    const path = block.match(/^worktree (.+)$/m)?.[1];
    if (path && resolve(path) !== resolve(top) && block.split("\n").includes(`branch refs/heads/${branch}`)) return path;
  }
  return undefined;
};

const loopAlive = () => {
  const f = ".sandcastle/loop.pid";
  if (!existsSync(f)) return false;
  const pid = Number(readFileSync(f, "utf8").trim());
  try { process.kill(pid, 0); return pid; } catch { return false; }
};

// ---- Slack, with the loop's own webhooks (.sandcastle/.env, never printed)

const envOf = () => {
  const out = {};
  for (const f of [".sandcastle/.env"]) {
    if (!existsSync(f)) continue;
    for (const line of readFileSync(f, "utf8").split("\n")) {
      const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/);
      if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
  return { ...out, ...process.env };
};
const notify = async (kind, text) => {
  const env = envOf();
  const url = kind === "alert" ? env.SLACK_ALERTS_WEBHOOK_URL : env.SLACK_FEED_WEBHOOK_URL;
  if (!url) return false;
  const mention = kind === "alert" && env.SLACK_USER_ID ? `<@${env.SLACK_USER_ID}> ` : "";
  await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ text: `[${repo}] ${mention}run-ticket: ${text}` }) }).catch(() => {});
  return true;
};

const syncTracker = () => {
  if (!existsSync("tracker/build.mjs")) return false;
  run(process.execPath, ["tracker/build.mjs", "--no-open"], { timeout: 120_000 });
  return true;
};

// The epic branch with main merged in, pushed, in a temporary worktree (the
// loop or the user may hold the branch elsewhere). Returns a note. One ticket
// lands after it, and that push runs CI, so no [skip ci] here.
const updateEpicBranch = (epic) => {
  const exists = tryGit("rev-parse", "--verify", "--quiet", `origin/${epic.branch}`);
  const tmp = mkdtempSync(join(tmpdir(), "run-ticket-"));
  try {
    git("worktree", "add", "--quiet", "--detach", tmp, exists ? `origin/${epic.branch}` : "origin/main");
    if (exists && !run("git", ["-C", tmp, "merge", "--quiet", "-m", `Merge main into ${epic.branch}`, "origin/main"]).ok) {
      run("git", ["-C", tmp, "merge", "--abort"]);
      stop(`\`main\` conflicts with \`${epic.branch}\`. Resolve it first:\n\n\`\`\`sh\ngit switch --detach origin/${epic.branch}\ngit merge origin/main   # fix, commit\ngit push origin HEAD:${epic.branch}\ngit switch -\n\`\`\``, "Epic branch not ready");
    }
    const head = git("-C", tmp, "rev-parse", "HEAD");
    if (!exists || head !== git("rev-parse", `origin/${epic.branch}`)) {
      git("-C", tmp, "push", "--quiet", "origin", `HEAD:refs/heads/${epic.branch}`);
      git("fetch", "--quiet", "origin", epic.branch);
      return exists ? "main merged in and pushed" : "created from main and pushed";
    }
    return "already up to date with main";
  } finally {
    run("git", ["worktree", "remove", "--force", tmp]);
    rmSync(tmp, { recursive: true, force: true });
  }
};

const installIn = (path) => {
  const pm = existsSync(join(path, "pnpm-lock.yaml")) ? ["pnpm", ["install", "--frozen-lockfile", "--prefer-offline"]]
    : existsSync(join(path, "yarn.lock")) ? ["yarn", ["install", "--immutable"]]
    : existsSync(join(path, "package-lock.json")) ? ["npm", ["ci"]]
    : null;
  if (!pm) return "no lockfile, nothing installed";
  const r = run(pm[0], pm[1], { cwd: path, timeout: 600_000 });
  return r.ok ? `${pm[0]} install ok` : `${pm[0]} install FAILED: ${r.err.slice(-400)}`;
};

// The epic's milestone with nothing open but the epic (backlog items don't
// count, as for the loop): its PR to main can go up.
const epicBuilt = (epic) =>
  ghJson("issue", "list", "--state", "open", "--milestone", epic.milestone, "--json", "number,labels", "--limit", "200")
    .filter((i) => i.number !== epic.number && !i.labels.some((l) => l.name === LABEL.backlog)).length === 0;

// The epic's PR, as /run-epic's `finish` opens it (main merged in once more).
const openEpicPr = (epic) => {
  const existing = ghJson("pr", "list", "--head", epic.branch, "--base", "main", "--state", "open", "--json", "number,url", "--limit", "1")[0];
  if (existing) return { url: existing.url, opened: false };
  updateEpicBranch(epic);
  const closed = ghJson("issue", "list", "--state", "closed", "--milestone", epic.milestone, "--json", "number,title,labels,body", "--limit", "200")
    .filter((i) => i.number !== epic.number && !isSpec(i.labels.map((l) => l.name), i.body) && !i.labels.some((l) => l.name.startsWith("wayfinder:")))
    .sort((a, b) => a.number - b.number);
  const spec = ghJson("issue", "list", "--state", "all", "--milestone", epic.milestone, "--label", LABEL.spec, "--json", "number", "--limit", "1")[0];
  const destination = epic.body.match(/## Destination\s+([\s\S]*?)(?:\n## |\s*$)/)?.[1]?.trim() ?? "";
  const body = `**Epic:** #${epic.number}${spec ? ` · **Spec:** #${spec.number}` : ""}\n\n${destination}\n\n## Tickets\n\n${closed.map((i) => `- #${i.number} ${i.title}`).join("\n")}\n\n${AI_NOTE} Built ticket by ticket on \`${epic.branch}\`; run \`/verify-epic\` on this PR before merging.\n\nCloses #${epic.number}`;
  return { url: gh("pr", "create", "--base", "main", "--head", epic.branch, "--title", `Epic: ${epic.title}`, "--body", body), opened: true };
};

// ---- commands

const commands = {
  check([n]) {
    if (!n) stop("Usage: check <ticket> [--force]");
    const auth = run("gh", ["api", "user", "--jq", ".login"]);
    if (!auth.ok) stop("`gh` isn't logged in: run `gh auth login`.");
    const dirty = git("status", "--porcelain", "--untracked-files=no");
    if (dirty) stop(`The checkout has uncommitted changes. Commit or stash them first:\n\n\`\`\`\n${dirty}\n\`\`\``);
    if (!run("git", ["fetch", "--quiet", "origin"]).ok) stop("Couldn't fetch `origin`.");
    const t = ticketOf(n);
    const force = flags.has("--force");
    if (t.state !== "OPEN") stop(`#${n} is closed.`);
    if (t.labels.includes(LABEL.epic)) stop(`#${n} is an epic, not a ticket: \`/run-epic ${n}\` builds its tickets.`, "Not a ticket");
    if (isSpec(t.labels, t.body)) stop(`#${n} is a spec: \`/to-tickets\` turns it into tickets, which are built instead.`, "Not a ticket");
    if (t.labels.some((l) => l.startsWith("wayfinder:"))) stop(`#${n} is a wayfinder map or decision ticket, worked with \`/wayfinder\`, not built.`, "Not a ticket");
    if (t.labels.includes(LABEL.backlog) && !force) stop(`#${n} is in the backlog (\`${LABEL.backlog}\`). Remove the label first, or \`--force\` on the user's word.`, "Parked");
    // A ticket the agents can build: queued for them, or one a person was to
    // build (a manual epic's tickets, a small `ready-for-human` enhancement).
    if (![LABEL.build, LABEL.bug, LABEL.human].some((l) => t.labels.includes(l)) && !force)
      stop(`#${n} carries none of \`${LABEL.build}\`, \`${LABEL.bug}\` or \`${LABEL.human}\`, so it hasn't been triaged into a buildable ticket. \`/triage #${n}\` first, or \`--force\` on the user's word.`, "Not ready");
    const others = t.assignees.filter((a) => a !== me);
    if (others.length) stop(`#${n} is claimed by ${others.map((a) => `@${a}`).join(", ")}.`, "Claimed");
    const loop = loopAlive();
    // The loop claims with the user's own account: assigned to them with a
    // loop running here may be the loop building it.
    if (t.assignees.includes(me) && loop && !force)
      stop(`#${n} is assigned to you and the agent loop is running here (pid ${loop}): it may be building it. Stop the loop (\`npm run agents:stop\`) or pick another ticket; \`--force\` only on the user's word that the loop isn't on it.`, "The loop may be on it", 2);
    const elsewhere = branchWorktree(t.branch);
    if (elsewhere && resolve(elsewhere) !== resolve(wtPath(n)))
      stop(`\`${t.branch}\` is checked out in \`${elsewhere}\` (a loop sandbox, or another session). If nothing is running there, \`git worktree remove ${elsewhere}\` and run again.`, "Branch in use");
    const open = blockers(n);
    if (open.length && !force) stop(`#${n} is blocked by ${open.map((b) => `#${b}`).join(", ")}. Build those first, or \`--force\` on the user's word.`, "Blocked");
    const env = envOf();
    json({
      me,
      ticket: { number: t.number, title: t.title, kind: t.kind, labels: t.labels, branch: t.branch, base: t.base, lands: t.epic ? `on ${t.epic.branch}, closed with the loop's wording` : `as a PR to main ("Fixes #${t.number}"), labelled ${LABEL.review}` },
      epic: t.epic ? { number: t.epic.number, title: t.epic.title, branch: t.epic.branch, milestone: t.epic.milestone, manual: t.epic.manual, blockedByEpics: blockedCount(t.epic.number) } : null,
      notes: [
        ...(t.labels.includes(LABEL.human) ? [`#${n} is \`${LABEL.human}\`: a person was meant to act on it. Read the issue for why before building; if it waits on a decision or access, stop.`] : []),
        ...(open.length ? [`blocked by ${open.map((b) => `#${b}`).join(", ")}, run anyway (--force)`] : []),
        ...(loop && !t.assignees.includes(me) ? [`the agent loop is running here (pid ${loop}); claiming #${n} first keeps it away, since the loop only takes unassigned tickets`] : []),
      ],
      loop: { running: loop || false },
      services: { setup: existsSync(".sandcastle/sandbox-setup.sh") ? readFileSync(".sandcastle/sandbox-setup.sh", "utf8").split("\n").filter((l) => l.startsWith("#")).slice(0, 12).join("\n") : null, devUp: /"dev:up"/.test(existsSync("package.json") ? readFileSync("package.json", "utf8") : "") ? "pnpm dev:up / npm run dev:up" : null },
      slack: { feed: Boolean(env.SLACK_FEED_WEBHOOK_URL), alerts: Boolean(env.SLACK_ALERTS_WEBHOOK_URL) },
      tracker: existsSync("tracker/build.mjs"),
      prompts: ["implement", "bug", "review"].map((k) => promptPath(k)),
    });
  },

  prepare([n]) {
    if (!n) stop("Usage: prepare <ticket> [--retry]");
    const t = ticketOf(n);
    if (t.state !== "OPEN") stop(`#${n} is closed.`);
    const others = t.assignees.filter((a) => a !== me);
    if (others.length) stop(`#${n} is claimed by ${others.map((a) => `@${a}`).join(", ")}.`);
    if (!t.assignees.includes(me)) {
      gh("issue", "edit", String(n), "--add-assignee", "@me");
      const now = ghJson("issue", "view", String(n), "--json", "assignees").assignees.map((a) => a.login);
      if (!(now.length === 1 && now[0] === me)) { gh("issue", "edit", String(n), "--remove-assignee", "@me"); stop(`Someone claimed #${n} at the same moment.`); }
    }
    git("fetch", "--quiet", "origin");
    const baseNote = t.epic ? updateEpicBranch(t.epic) : "off origin/main";
    const path = wtPath(n);
    // --retry: the branch conflicted with the epic branch at landing; as the
    // loop does, drop it and rebuild on top of the latest epic branch.
    if (flags.has("--retry")) {
      run("git", ["worktree", "remove", "--force", path]);
      tryGit("branch", "-D", t.branch);
      tryGit("push", "--quiet", "origin", "--delete", t.branch);
    }
    if (existsSync(path)) run("git", ["worktree", "remove", "--force", path]);
    tryGit("worktree", "prune");
    mkdirSync(WORKTREES, { recursive: true });
    let branchNote;
    if (tryGit("rev-parse", "--verify", "--quiet", `refs/heads/${t.branch}`)) {
      const elsewhere = branchWorktree(t.branch);
      if (elsewhere && resolve(elsewhere) !== resolve(path)) stop(`\`${t.branch}\` is checked out in \`${elsewhere}\`. If no agent is running there, \`git worktree remove ${elsewhere}\` and run again.`, `Claimed #${n}, but its branch isn't ready`);
      git("worktree", "add", "--quiet", path, t.branch);
      branchNote = "existing local branch, earlier work kept";
    } else if (tryGit("rev-parse", "--verify", "--quiet", `refs/remotes/origin/${t.branch}`)) {
      git("worktree", "add", "--quiet", "--track", "-b", t.branch, path, `origin/${t.branch}`);
      branchNote = `from origin/${t.branch}, which already had work`;
    } else {
      git("worktree", "add", "--quiet", "--no-track", "-b", t.branch, path, t.base);
      branchNote = `new, from ${t.base}`;
    }
    const [behind, ahead] = git("rev-list", "--left-right", "--count", `${t.base}...${t.branch}`).split(/\s+/).map(Number);
    const install = flags.has("--no-install") ? "skipped" : installIn(path);
    json({ ticket: { number: t.number, title: t.title, kind: t.kind, branch: t.branch, base: t.base }, epic: t.epic ? { number: t.epic.number, title: t.epic.title, branch: t.epic.branch } : null, baseNote, worktree: path, branchNote, ahead, behind, install });
  },

  prompt([kind, n]) {
    if (!["implement", "bug", "review"].includes(kind) || !n) stop("Usage: prompt <implement|bug|review> <ticket>");
    const t = ticketOf(n);
    const path = wtPath(n);
    if (!existsSync(path)) stop(`No worktree for #${n}: run \`prepare ${n}\` first.`);
    let text = readFileSync(promptPath(kind), "utf8")
      .replaceAll("{{ISSUE}}", String(t.number)).replaceAll("{{TITLE}}", t.title).replaceAll("{{BRANCH}}", t.branch).replaceAll("{{BASE}}", t.base);
    // Sandcastle expands !`cmd` lines at run time; do the same here, in the worktree.
    text = text.replace(/^!`([^`]+)`$/gm, (_, c) => { const r = run("sh", ["-c", c], { cwd: path }); return "```\n" + (r.ok ? r.out : r.err).slice(0, 60_000) + "\n```"; });
    const services = existsSync(".sandcastle/sandbox-setup.sh")
      ? "The services a sandbox would start (see `.sandcastle/sandbox-setup.sh`) are already running on this machine; the operator confirmed it. `source .sandcastle/sandbox-env` doesn't apply here."
      : "The project's services are already running on this machine; the operator confirmed it.";
    const preamble = `# RUN-TICKET

You are run by \`/run-ticket\`: the agent loop's pipeline, inside a Claude Code session on the developer's machine, not in a sandbox. Work **only** in the git worktree \`${path}\`: \`cd\` there first; it is on branch \`${t.branch}\` (base \`${t.base}\`), dependencies installed. Never switch branches, push, open PRs, or touch any other checkout or worktree; the session lands the work. ${services} Don't install or start infrastructure of your own. Stop every process you started before finishing. Instead of a \`<promise>\` line, end with a short report: the commits you made (or why you made none), and what you ran.

---

`;
    process.stdout.write(preamble + text + "\n");
  },

  commits([n]) {
    if (!n) stop("Usage: commits <ticket>");
    const t = ticketOf(n);
    git("fetch", "--quiet", "origin", t.baseRef);
    console.log(git("rev-list", "--count", `${t.base}..${t.branch}`));
  },

  async land([n]) {
    if (!n) stop("Usage: land <ticket>");
    const t = ticketOf(n);
    git("fetch", "--quiet", "origin");

    // No epic: the loop's standalone landing, a PR to main for a person to merge.
    if (!t.epic) {
      git("-C", wtPath(n), "push", "--quiet", "-u", "origin", t.branch);
      const existing = ghJson("pr", "list", "--head", t.branch, "--base", "main", "--state", "open", "--json", "url", "--limit", "1")[0];
      const url = existing?.url ?? gh("pr", "create", "--base", "main", "--head", t.branch, "--title", t.title, "--body",
        `Fixes #${n}\n\n${AI_NOTE} See the issue for the reasoning and evidence.`);
      const edit = ["issue", "edit", String(n), "--add-label", LABEL.review];
      for (const l of [LABEL.build, LABEL.bug, LABEL.human]) if (t.labels.includes(l)) edit.push("--remove-label", l);
      gh(...edit);
      run("git", ["worktree", "remove", "--force", wtPath(n)]); // the branch stays, for the PR's fixes
      const tracker = syncTracker();
      const slack = await notify("feed", `#${n} ${t.title} → ${url}`);
      json({ landed: n, pr: url, prExisted: Boolean(existing), branch: t.branch, tracker, slack });
      return;
    }

    // Under an epic: merge onto the epic branch, as the loop lands a ticket.
    const tmp = mkdtempSync(join(tmpdir(), "run-ticket-land-"));
    let sha;
    try {
      git("worktree", "add", "--quiet", "--detach", tmp, `origin/${t.epic.branch}`);
      if (!run("git", ["-C", tmp, "merge", "--no-edit", "--quiet", t.branch]).ok) {
        run("git", ["-C", tmp, "merge", "--abort"]);
        stop(`\`${t.branch}\` conflicts with \`${t.epic.branch}\`. As the loop would, rebuild it on top of the latest epic branch: \`prepare ${n} --retry\`, then build again.`, "Merge conflict", 3);
      }
      git("-C", tmp, "push", "--quiet", "origin", `HEAD:${t.epic.branch}`);
      sha = git("-C", tmp, "rev-parse", "--short", "HEAD");
    } finally {
      run("git", ["worktree", "remove", "--force", tmp]);
      rmSync(tmp, { recursive: true, force: true });
    }
    git("fetch", "--quiet", "origin", t.epic.branch);
    gh("issue", "close", String(n), "--comment", `${AI_NOTE}\n\nLanded on \`${t.epic.branch}\` in ${sha}. It ships with the epic's PR (#${t.epic.number}).`);
    run("git", ["worktree", "remove", "--force", wtPath(n)]);
    tryGit("branch", "-D", t.branch);
    tryGit("push", "--quiet", "origin", "--delete", t.branch);
    // The epic's last ticket: its PR goes up, as /run-epic's finish (or the
    // loop's next pass) would open it.
    const epicPr = epicBuilt(t.epic) ? openEpicPr(t.epic) : null;
    const tracker = syncTracker();
    const slack = await notify("feed", `#${n} ${t.title} landed on ${t.epic.branch} (${sha}).${epicPr?.opened ? ` Epic #${t.epic.number} is built: ${epicPr.url}` : ""} https://github.com/${repo}/issues/${n}`);
    json({ landed: n, sha, epicBranch: t.epic.branch, epicBuilt: Boolean(epicPr), epicPr: epicPr?.url ?? null, epicPrOpened: epicPr?.opened ?? false, tracker, slack });
  },

  async handback([n, ...why]) {
    if (!n) stop("Usage: handback <ticket> <reason>");
    const reason = why.join(" ") || "the agent made no commits";
    const t = ticketOf(n);
    const swap = [LABEL.build, LABEL.bug].find((l) => t.labels.includes(l));
    const argv = ["issue", "edit", String(n), "--remove-assignee", "@me"];
    if (swap) argv.push("--remove-label", swap);
    if (!t.labels.includes(LABEL.human)) argv.push("--add-label", LABEL.human);
    gh(...argv);
    gh("issue", "comment", String(n), "--body", `${AI_NOTE}\n\nHanded to a person by /run-ticket: ${reason}\n\nThe branch \`${t.branch}\` keeps any work; \`/claim ${n}\` or \`/run-ticket ${n}\` resumes it.`);
    run("git", ["worktree", "remove", "--force", wtPath(n)]);
    const tracker = syncTracker();
    const slack = await notify("alert", `#${n} ${t.title} handed to a person: ${reason} https://github.com/${repo}/issues/${n}`);
    json({ handedBack: n, reason, tracker, slack });
  },

  async notify([kind, ...text]) {
    if (!["feed", "alert"].includes(kind) || !text.length) stop("Usage: notify <feed|alert> <text>");
    json({ sent: await notify(kind, text.join(" ")) });
  },
};

// The loop's prompts: the project's copies first (what its loop runs), else
// this repo's templates next to the setup skill.
function promptPath(kind) {
  const local = `.sandcastle/${kind}-prompt.md`;
  if (existsSync(local)) return local;
  const shipped = resolve(HERE, "..", "..", "setup-imick-skills", "agent-loop", `${kind}-prompt.md`);
  if (existsSync(shipped)) return shipped;
  stop(`No ${kind} prompt: neither \`${local}\` nor the setup skill's template exists. Run /setup-imick-skills (section F) or install the skills with their setup skill.`);
}

